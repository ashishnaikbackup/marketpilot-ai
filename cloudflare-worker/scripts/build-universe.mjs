// Builds src/universe-india.js from Upstox's public NSE instrument master.
// Run by .github/workflows/refresh-universe.yml (the Worker cannot download this file itself).
//   node scripts/build-universe.mjs [path-to-NSE.json]   (default: download NSE.json.gz)
import { gunzipSync } from "node:zlib";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const SOURCE = "https://assets.upstox.com/market-quote/instruments/exchange/NSE.json.gz";
const INDEX_UNDERLYINGS = { NIFTY: "Nifty 50", BANKNIFTY: "Nifty Bank", FINNIFTY: "Nifty Fin Service", MIDCPNIFTY: "NIFTY MID SELECT", NIFTYNXT50: "Nifty Next 50" };
const isoDay = (ms) => new Date(Number(ms) + 330 * 60000).toISOString().slice(0, 10);

/** Pure: instrument-master rows → universe. Defensive about field names so a feed tweak fails loudly, not silently. */
export function buildUniverse(rows, nowMs = Date.now()) {
  const today = isoDay(nowMs);
  const opts = rows.filter((r) => r.segment === "NSE_FO" && ["CE", "PE"].includes(r.instrument_type) && r.underlying_symbol);
  const byUnder = new Map();
  for (const r of opts) {
    const g = byUnder.get(r.underlying_symbol) || { key: r.underlying_key, lot: r.lot_size, expiries: new Set() };
    const e = r.expiry ? isoDay(r.expiry) : null;
    if (e && e >= today) g.expiries.add(e);
    byUnder.set(r.underlying_symbol, g);
  }
  const indexRows = rows.filter((r) => r.segment === "NSE_INDEX");
  const indices = [];
  for (const [symbol, nm] of Object.entries(INDEX_UNDERLYINGS)) {
    const g = byUnder.get(symbol); if (!g) continue;
    const row = indexRows.find((r) => r.instrument_key === g.key) || indexRows.find((r) => String(r.name || r.trading_symbol).toLowerCase() === nm.toLowerCase());
    indices.push({ symbol, key: g.key || row?.instrument_key, name: row?.name || nm, lot_size: g.lot || undefined, expiries: [...g.expiries].sort() });
  }
  const eq = rows.filter((r) => r.segment === "NSE_EQ" && r.instrument_type === "EQ" && r.trading_symbol && r.instrument_key);
  const isEtf = (r) => /\b(ETF|BEES|ETFS)\b/i.test(`${r.name || ""} ${r.trading_symbol}`) || /BEES$/i.test(r.trading_symbol);
  const fnoKeys = new Set([...byUnder.values()].map((g) => g.key));
  const stocks = eq.filter((r) => fnoKeys.has(r.instrument_key) && !isEtf(r)).map((r) => {
    const g = byUnder.get(r.trading_symbol) || [...byUnder.values()].find((x) => x.key === r.instrument_key);
    return { symbol: r.trading_symbol, key: r.instrument_key, name: r.name, lot_size: g.lot, expiries: [...g.expiries].sort() };
  }).filter((s) => Number.isInteger(s.lot_size) && s.lot_size > 0 && s.expiries.length).sort((a, b) => a.symbol.localeCompare(b.symbol));
  const etfs = eq.filter(isEtf).map((r) => ({ symbol: r.trading_symbol, key: r.instrument_key, name: r.name })).sort((a, b) => a.symbol.localeCompare(b.symbol));
  if (indices.length < 2 || stocks.length < 50) throw new Error(`Instrument master looks wrong (indices ${indices.length}, F&O stocks ${stocks.length}); refusing to overwrite the universe.`);
  return { generated_at: new Date(nowMs).toISOString(), source: SOURCE, indices, stocks, etfs };
}

export const render = (u) => `// Indian market universe. GENERATED by scripts/build-universe.mjs (workflow "Refresh India universe"). Do not edit by hand.\nexport default ${JSON.stringify(u, null, 1)};\n`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const arg = process.argv[2];
  const raw = arg ? readFileSync(arg) : Buffer.from(await (await fetch(SOURCE)).arrayBuffer());
  const rows = JSON.parse((arg && !arg.endsWith(".gz") ? raw : gunzipSync(raw)).toString("utf8"));
  const u = buildUniverse(rows);
  writeFileSync(new URL("../src/universe-india.js", import.meta.url), render(u));
  console.log(`Universe: ${u.indices.length} indices, ${u.stocks.length} F&O stocks, ${u.etfs.length} ETFs`);
}
